import { expect, test, type Page } from '@playwright/test'
import { newGame, runMission, type Game } from '../src/game/mission'

import { button, configure, enterMeeting, finishWork, firstBrief, meeting, reveal, useStudioClock, work } from './studio-controls'
const radio = (page: Page, name: RegExp) => page.getByRole('radio', { name })
const persisted = (page: Page): Promise<Game> => page.evaluate(() => JSON.parse(localStorage.getItem('space-mission.single.v2')!))

async function start(page: Page, seed: number, { bay = false, rideshare = false, capability }: {
  bay?: boolean; rideshare?: boolean; capability?: RegExp
} = {}) {
  await page.goto(`/?seed=${seed}`)
  await firstBrief(page)
  if (bay) await radio(page, /Bay discharge survey/).check()
  await button(page, 'Accept commission').click()
  await enterMeeting(page)
  if (rideshare) await configure(page, /^Launch and orbit/, /Rideshare to sun-synchronous orbit/)
  if (capability) await configure(page, /^Observation capability/, capability)
  if (!(await meeting(page).isVisible())) await button(page, 'Compare designs').click()
  await work(page, /^Confirm initial configuration/)
}

async function integrate(page: Page) {
  await work(page, /^Freeze design/)
  await work(page, /^Build and test subsystems/)
  await work(page, /^Run integration tests/)
  await reviewConditions(page)
  await enterMeeting(page)
  await expect(page.locator('.studio-release').getByText(/first transmission T\+32 min.*minimum silence 30 min/)).toBeVisible()
}

async function pass(page: Page) {
  await reviewConditions(page)
  await button(page, 'Submit FRR').click()
  await button(page, 'Launch vehicle').click()
  await button(page, 'Go to mission control').click()
  await button(page, 'Run first ground pass').click()
}

async function reviewConditions(page: Page) {
  const review = button(page, 'Review release conditions')
  if (await review.isVisible()) await review.click()
}

